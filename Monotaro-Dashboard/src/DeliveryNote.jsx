import { shippedCount } from './data.js'

const v = (x) => x || '—'

// Paper version of an order's delivery data; only visible when printing.
export default function DeliveryNote({ order, db }) {
  const c = db.customers.find((x) => x.id === order.customerAccountId)
  const a = db.deliveryAddresses.find((x) => x.id === order.deliveryAddressId)
  const d = order.delivery
  const sku = (id) => db.productSkus.find((s) => s.id === id)
  const { ordered, shipped } = shippedCount(order)

  return (
    <article className="note">
      <header className="note-head">
        <img src="/Logo.png" alt="Monotaro.id" />
        <h1>Delivery Note</h1>
      </header>

      <div className="note-meta">
        <dl>
          <dt>Ship to</dt><dd>{a.receiverName}</dd>
          <dt>PIC</dt><dd>{c.fullname}{c.companyName && ` · ${c.companyName}`}</dd>
          <dt>Phone</dt><dd>{a.receiverPhoneNumber}</dd>
          <dt>Order date</dt><dd>{order.orderDate}</dd>
          <dt>SO No</dt><dd>{v(d.soNumber)}</dd>
          <dt>DO No</dt><dd>{v(d.doNumber)}</dd>
          <dt>PO No</dt><dd>{v(d.poNumber)}</dd>
        </dl>
        <dl>
          <dt>Address</dt><dd>{a.detailedAddress}, {a.regionAddress}</dd>
          <dt>AWB</dt><dd>{v(d.awbNumber)}</dd>
          <dt>Transport</dt><dd>{v(d.courierCompanyName || d.deliveryMethod)}</dd>
          <dt>Payment</dt><dd>{order.paymentMethod}</dd>
          <dt>Delivery date</dt><dd>{v(d.deliveryDate)}</dd>
          <dt>Printed</dt><dd>{d.printCount ?? 1}×</dd>
        </dl>
      </div>

      <table>
        <thead>
          <tr><th>No</th><th>Product</th><th>Ordered</th><th>Shipped</th><th>Remaining</th></tr>
        </thead>
        <tbody>
          {order.items.map((i, k) => (
            <tr key={i.productSkuId}>
              <td>{k + 1}</td>
              <td>{sku(i.productSkuId)?.skuNumber} · {sku(i.productSkuId)?.name}</td>
              <td>{i.quantity}</td>
              <td>{i.shippedQty ?? 0}</td>
              <td>{i.quantity - (i.shippedQty ?? 0)}</td>
            </tr>
          ))}
        </tbody>
        <tfoot>
          <tr><td colSpan={2}>Total</td><td>{ordered}</td><td>{shipped}</td><td>{ordered - shipped}</td></tr>
        </tfoot>
      </table>

      {d.note && <p className="note-remark"><strong>Note:</strong> {d.note}</p>}

      <div className="note-sign">
        <div><span>Warehouse by</span><span className="line" /><span>Date:</span></div>
        <div><span>Delivered by</span><span className="line" /><span>Date:</span></div>
        <div><span>Received by</span><span className="line" /><span>Date:</span></div>
      </div>

      <footer className="note-foot">
        <p>Please check that the goods and quantities match this note when you receive them.</p>
        <p>Items not shipped yet will follow in a later delivery. Report missing or damaged goods within 14 days.</p>
        <p className="muted">Demo document generated by Monotaro Dashboard · Order #{order.id}</p>
      </footer>
    </article>
  )
}
